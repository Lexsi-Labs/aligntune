import os
os.environ["CUDA_VISIBLE_DEVICES"] = "0"
import sys
import json
import torch
import gc
from pathlib import Path
import traceback

from aligntune.core.backend_factory import create_rl_trainer
from aligntune.eval.runner import EvalConfig, run_eval
import aligntune

"""## Configuration"""

# Model and Dataset
BASE_MODEL = "Qwen/Qwen3-4B-Instruct-2507"
SFT_MODEL = "sohamb37lexsi/wealth_management_Qwen3-4B-Instruct-2507"
PREFERENCE_DATASET = "sohamb37lexsi/bitext_wealth_management_preference_data"
EVAL_DATASET = "sohamb37lexsi/bitext-wealth-management-llm-chatbot-splits"

# Output Directories
DPO_OUTPUT_DIR = "./output/dpo_wealth_management"
DPO_EVAL_DIR = f"{DPO_OUTPUT_DIR}/eval_results_dpo"
SFT_EVAL_DIR = "./output/eval_results_sft"
BASE_EVAL_DIR = "./output/eval_results_base"

# DPO Training Hyperparameters
NUM_EPOCHS = 3
MAX_STEPS = -1  # Let epochs control duration
BATCH_SIZE = 8
GRADIENT_ACCUMULATION_STEPS = 2
LEARNING_RATE = 5e-5
MAX_SEQ_LENGTH = 1512

# DPO-Specific Parameters
DPO_BETA = 0.01
LABEL_SMOOTHING = 0.1
LOSS_TYPE = "sft"

# LoRA Configuration
USE_LORA = True
LORA_R = 16
LORA_ALPHA = 32
LORA_DROPOUT = 0.05
LORA_TARGET_MODULES = ["q_proj", "v_proj", "k_proj", "o_proj"]

# Quantization
QUANTIZATION = {
    "load_in_4bit": True,
    "bnb_4bit_compute_dtype": "float16"
}

# Precision
PRECISION = "fp16"

# Evaluation Parameters
EVAL_BATCH_SIZE = 16
EVAL_MAX_LENGTH = 1512
EVAL_MAX_SAMPLES = None

"""## Utility Functions"""

def cleanup_memory():
    """Clear GPU memory and cache."""
    gc.collect()
    torch.cuda.empty_cache()
    if torch.cuda.is_available():
        torch.cuda.synchronize()

def print_gpu_utilization():
    """Print current GPU memory usage."""
    if torch.cuda.is_available():
        print(f"\nGPU Memory Usage:")
        for i in range(torch.cuda.device_count()):
            allocated = torch.cuda.memory_allocated(i) / 1024**3
            reserved = torch.cuda.memory_reserved(i) / 1024**3
            print(f"  GPU {i}: {allocated:.2f}GB allocated, {reserved:.2f}GB reserved")

def save_training_config(output_dir: str, config_name: str = "dpo_training_config.json"):
    """Save training configuration to JSON file."""
    config = {
        "base_model": BASE_MODEL,
        "sft_model": SFT_MODEL,
        "preference_dataset": PREFERENCE_DATASET,
        "eval_dataset": EVAL_DATASET,
        "algorithm": "dpo",
        "num_epochs": NUM_EPOCHS,
        "batch_size": BATCH_SIZE,
        "gradient_accumulation_steps": GRADIENT_ACCUMULATION_STEPS,
        "learning_rate": LEARNING_RATE,
        "max_seq_length": MAX_SEQ_LENGTH,
        "dpo_beta": DPO_BETA,
        "label_smoothing": LABEL_SMOOTHING,
        "loss_type": LOSS_TYPE,
        "use_lora": USE_LORA,
        "lora_config": {
            "r": LORA_R,
            "alpha": LORA_ALPHA,
            "dropout": LORA_DROPOUT,
            "target_modules": LORA_TARGET_MODULES
        }
    }

    config_path = Path(output_dir) / config_name
    config_path.parent.mkdir(parents=True, exist_ok=True)

    with open(config_path, "w") as f:
        json.dump(config, f, indent=2)

    print(f"Configuration saved to: {config_path}")

"""## DPO Training Function"""

def run_dpo_training():
    """Executes the DPO training loop."""
    results = {
        "model": SFT_MODEL,
        "output_dir": DPO_OUTPUT_DIR
    }

    print("\n" + "=" * 80)
    print("STEP 1: TRAINING MODEL WITH DPO")
    print("=" * 80)
    print(f"Base SFT Model: {SFT_MODEL}")
    print(f"Preference Dataset: {PREFERENCE_DATASET}")

    # Create output directory and save config
    Path(DPO_OUTPUT_DIR).mkdir(parents=True, exist_ok=True)
    save_training_config(DPO_OUTPUT_DIR)
    print_gpu_utilization()

    try:
        print("\n🚀 Creating DPO trainer with TRL backend...")

        trainer = create_rl_trainer(
            model_name=SFT_MODEL,
            dataset_name=PREFERENCE_DATASET,
            algorithm="dpo",
            split="train",
            backend="trl",

            # Training parameters
            num_epochs=NUM_EPOCHS,
            max_steps=MAX_STEPS,
            batch_size=BATCH_SIZE,
            learning_rate=LEARNING_RATE,
            max_seq_length=MAX_SEQ_LENGTH,

            # DPO-specific parameters
            beta=DPO_BETA,
            label_smoothing=LABEL_SMOOTHING,
            loss_type=LOSS_TYPE,

            # Optimization parameters
            gradient_accumulation_steps=GRADIENT_ACCUMULATION_STEPS,
            warmup_ratio=0.1,
            warmup_steps=100,
            weight_decay=0.01,
            max_grad_norm=1.0,
            lr_scheduler_type="cosine",

            # Regularization
            dropout=0.1,

            # Evaluation & logging
            eval_steps=100,
            save_steps=200,
            logging_steps=10,
            save_total_limit=3,
            eval_strategy="no",  # no eval_dataset/eval_split is configured for the training loop;
                                 # this script evaluates separately post-training via run_evaluation()

            # Reference model settings
            precompute_ref_log_probs=True,

            # Generation settings
            max_new_tokens=512,
            temperature=0.7,
            top_p=0.9,

            # Memory optimization
            gradient_checkpointing=True,
            optim="adamw_torch",

            # LoRA settings
            use_lora=USE_LORA,
            lora_r=LORA_R,
            lora_alpha=LORA_ALPHA,
            lora_dropout=LORA_DROPOUT,
            lora_target_modules=LORA_TARGET_MODULES,

            # System settings
            quantization=QUANTIZATION,
            output_dir=DPO_OUTPUT_DIR,
            loggers=["tensorboard"],
            precision=PRECISION,
        )

        print("✅ Trainer created successfully!")

        # Start training
        print("\n🏃 TRAINING IN PROGRESS...")
        training_results = trainer.train()

        print("\n" + "=" * 80)
        print("DPO Training completed successfully!")
        print("=" * 80)
        print(f"Model saved to: {training_results['model_path']}")
        print(f"Final loss: {training_results.get('final_loss', 'N/A')}")
        print(f"Training time: {training_results.get('training_time', 0):.2f}s")
        print(f"Total steps: {training_results.get('total_steps', 'N/A')}")

        trained_model_path = training_results["model_path"]
        results["training"] = training_results
        results["trained_model_path"] = trained_model_path
        results["status"] = "success"

        return results

    except Exception as e:
        print(f"\n❌ TRAINING FAILED: {e}")
        traceback.print_exc()
        return {"status": "failed", "error": str(e), "trained_model_path": None}

    finally:
        print("\n🧹 Cleaning up training memory...")
        cleanup_memory()

"""## Evaluation Function"""

def run_evaluation(model_path, use_lora=False, out_dir=None, model_label="Model"):
    """Executes evaluation on the specified model.

    Args:
        model_path: Path to the model to evaluate
        use_lora: Whether to use LoRA for the model
        out_dir: Output directory for evaluation results
        model_label: Label for the model (for logging)
    """
    print("\n" + "=" * 80)
    print(f"EVALUATING {model_label.upper()}")
    print("=" * 80)

    if not model_path:
        print(f"\n❌ No model path provided for {model_label}. Skipping evaluation.")
        return None

    try:
        print(f"\n>>> Evaluating {model_label} from: {model_path}")
        print(f">>> Using LoRA: {use_lora}")

        eval_config = EvalConfig(
            model_path=model_path,
            output_dir=out_dir,
            device="cuda",
            data_task_type="sft",
            metrics=["bleu", "rouge"],
            reference_model_path=BASE_MODEL,
            dataset_name=EVAL_DATASET,
            split="test",
            max_length=EVAL_MAX_LENGTH,
            batch_size=EVAL_BATCH_SIZE,
            max_samples=EVAL_MAX_SAMPLES,
            use_lora=use_lora,
        )

        print(f"📊 Running evaluation on test split...")
        print(f"📂 Evaluation results will be saved to: {out_dir}")

        results = run_eval(eval_config)

        print(f"\n✅ {model_label} Results:")
        print(json.dumps(results, indent=2))

        return results

    except Exception as e:
        print(f"\n❌ EVALUATION FAILED for {model_label}: {e}")
        traceback.print_exc()
        return None

    finally:
        print("\n🧹 Cleaning up evaluation memory...")
        cleanup_memory()

"""## Run DPO Training"""

print("\n" + "=" * 80)
print("DPO TRAINING & EVALUATION PIPELINE")
print("=" * 80)

train_results = run_dpo_training()

"""## Evaluate DPO-Trained Model"""

if train_results.get("status") == "success":
    dpo_eval_results = run_evaluation(
        model_path=train_results.get("trained_model_path"),
        use_lora=USE_LORA,
        out_dir=DPO_EVAL_DIR,
        model_label="DPO-Trained Model"
    )

    print("\n" + "=" * 80)
    print("DPO TRAINING COMPLETED")
    print("=" * 80)
    print("✅ DPO Training: Success")
    print(f"✅ DPO Evaluation: {'Success' if dpo_eval_results else 'Failed'}")
else:
    print("\n❌ DPO training failed. Skipping DPO model evaluation.")
    dpo_eval_results = None

"""## Evaluate SFT Model (for comparison)"""

sft_eval_results = run_evaluation(
    model_path=SFT_MODEL,
    use_lora=False,
    out_dir=SFT_EVAL_DIR,
    model_label="SFT Model"
)

print("\n" + "=" * 80)
print("SFT MODEL EVALUATION COMPLETED")
print("=" * 80)
print(f"✅ Evaluation: {'Success' if sft_eval_results else 'Failed'}")

"""## Evaluate Base Model (for comparison)"""

base_eval_results = run_evaluation(
    model_path=BASE_MODEL,
    use_lora=False,
    out_dir=BASE_EVAL_DIR,
    model_label="Base Model"
)

print("\n" + "=" * 80)
print("BASE MODEL EVALUATION COMPLETED")
print("=" * 80)
print(f"✅ Evaluation: {'Success' if base_eval_results else 'Failed'}")

"""## Summary of Results"""

print("\n" + "=" * 80)
print("COMPLETE PIPELINE SUMMARY")
print("=" * 80)

print("\n📊 Training Status:")
print(f"  DPO Training: {'✅ Success' if train_results.get('status') == 'success' else '❌ Failed'}")

print("\n📊 Evaluation Status:")
print(f"  DPO Model: {'✅ Success' if dpo_eval_results else '❌ Failed/Skipped'}")
print(f"  SFT Model: {'✅ Success' if sft_eval_results else '❌ Failed'}")
print(f"  Base Model: {'✅ Success' if base_eval_results else '❌ Failed'}")

print("\n📁 Output Locations:")
if train_results.get("status") == "success":
    print(f"  DPO Model: {train_results.get('trained_model_path')}")
    print(f"  DPO Eval: {DPO_EVAL_DIR}")
print(f"  SFT Eval: {SFT_EVAL_DIR}")
print(f"  Base Eval: {BASE_EVAL_DIR}")

print("\n" + "=" * 80)

"""# Display Final Results"""

import pandas as pd
from pathlib import Path
import json

def load_and_display_results():
    """Load and display evaluation results in table format."""

    # Load results
    dpo_results = json.load(open(Path(DPO_EVAL_DIR) / "eval_results.json")) if (Path(DPO_EVAL_DIR) / "eval_results.json").exists() else None
    sft_results = json.load(open(Path(SFT_EVAL_DIR) / "eval_results.json")) if (Path(SFT_EVAL_DIR) / "eval_results.json").exists() else None
    base_results = json.load(open(Path(BASE_EVAL_DIR) / "eval_results.json")) if (Path(BASE_EVAL_DIR) / "eval_results.json").exists() else None

    # Extract metrics
    data = []
    for name, results in [("Base Model", base_results), ("SFT Model", sft_results), ("DPO Model", dpo_results)]:
        if results:
            metrics = results['metrics']
            data.append({
                'Model': name,
                'BLEU': f"{metrics['bleu']:.4f}",
                'ROUGE-1': f"{metrics['rouge1']:.4f}",
                'ROUGE-2': f"{metrics['rouge2']:.4f}",
                'ROUGE-L': f"{metrics['rougeL']:.4f}"
            })

    # Display table
    df = pd.DataFrame(data)
    print("\n" + "=" * 80)
    print("📊 EVALUATION RESULTS COMPARISON")
    print("=" * 80)
    print(df.to_string(index=False))
    print("=" * 80)

load_and_display_results()

