def print_dataset_comparison(dataset_name, results):
    """Print Pass@K comparison for a specific dataset"""
    print("\n" + "="*80)
    print(f"RESULTS ON {dataset_name.upper()}")
    print("="*80)

    base = results['base']
    dapo = results['dapo']

    # Extract Pass@K metrics (convert to percentages)
    base_p1 = base['pass_at_1'] * 100
    base_p2 = base['pass_at_2'] * 100
    base_p5 = base['pass_at_5'] * 100
    base_p10 = base['pass_at_10'] * 100

    dapo_p1 = dapo['pass_at_1'] * 100
    dapo_p2 = dapo['pass_at_2'] * 100
    dapo_p5 = dapo['pass_at_5'] * 100
    dapo_p10 = dapo['pass_at_10'] * 100

    # Pass@K Table
    print(f"\n{'Model':<20} {'Pass@1':<12} {'Pass@2':<12} {'Pass@5':<12} {'Pass@10':<12}")
    print("-" * 80)
    print(f"{'Base Model':<20} {base_p1:<12.2f} {base_p2:<12.2f} {base_p5:<12.2f} {base_p10:<12.2f}")
    print(f"{'DAPO (TRL)':<20} {dapo_p1:<12.2f} {dapo_p2:<12.2f} {dapo_p5:<12.2f} {dapo_p10:<12.2f}")

    # Improvements
    print(f"\n{'='*80}")
    print("IMPROVEMENTS OVER BASE MODEL")
    print(f"{'='*80}")

    print(f"\n{'Metric':<20} {'Absolute Δ':<15} {'Relative Δ (%)':<15}")
    print("-" * 80)

    for metric_name, dapo_val, base_val in [
        ('Pass@1', dapo_p1, base_p1),
        ('Pass@2', dapo_p2, base_p2),
        ('Pass@5', dapo_p5, base_p5),
        ('Pass@10', dapo_p10, base_p10)
    ]:
        abs_imp = dapo_val - base_val
        rel_imp = (abs_imp / base_val * 100) if base_val > 0 else 0
        print(f"{metric_name:<20} {abs_imp:+<15.2f} {rel_imp:+<15.2f}")

    return {
        'pass_at_1': dapo_p1 - base_p1,
        'pass_at_2': dapo_p2 - base_p2,
        'pass_at_5': dapo_p5 - base_p5,
        'pass_at_10': dapo_p10 - base_p10
    }

# Print comparison
