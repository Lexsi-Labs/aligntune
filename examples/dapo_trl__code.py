def cleanup_memory():
    """Aggressive memory cleanup"""
    gc.collect()
    torch.cuda.empty_cache()
    if torch.cuda.is_available():
        torch.cuda.synchronize()
    print("✓ Memory cleaned")

def run_evaluation(model_path, dataset_name, dataset_split, column_mapping,
                   output_dir, eval_name, use_lora=False, base_model=None):
    """Run evaluation on test set with Pass@K metrics."""
    dataset_short = dataset_name.split('/')[-1]
    print(f"\n>>> Evaluating {eval_name.upper()} model on {dataset_short.upper()}...")

    eval_config = EvalConfig(
        # Model & Hardware
        model_path=model_path,
        output_dir=f"{output_dir}/eval_{eval_name}_{dataset_short}",
        device="cuda",

        # Task & Metrics
        task_type="code",
        metrics=["pass_at_k"],
        k_list=[1, 2, 5, 10],

        # Dataset
        dataset_name=dataset_name,
        dataset_config=None,
        split=dataset_split,
        column_mapping=column_mapping,

        # Generation Parameters
        max_length=512,
        temperature=0.2,
        batch_size=8,
        max_samples=100,
        num_samples=10,

        # PEFT / Adapters
        use_lora=use_lora,
        base_model=base_model,
    )

    results = run_eval(eval_config)

    print(f"✓ {eval_name.upper()} on {dataset_short.upper()}:")
    print(f"  Pass@1: {results.get('pass_at_1', 0.0)*100:.2f}%")
    print(f"  Pass@10: {results.get('pass_at_10', 0.0)*100:.2f}%")

    cleanup_memory()

    return {
        'pass_at_1': results.get('pass_at_1', 0.0),
        'pass_at_2': results.get('pass_at_2', 0.0),
        'pass_at_5': results.get('pass_at_5', 0.0),
        'pass_at_10': results.get('pass_at_10', 0.0),
        'total_samples': results.get('total', 100),
        'output_dir': eval_config.output_dir
    }

